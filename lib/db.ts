function createClient() {
  const url = process.env.DATABASE_URL ?? ''
  // Only pin the CA when talking to Supabase; a local/other Postgres keeps
  // whatever the connection string specifies.
  const ssl = url.includes('supabase.com')
    ? { ca: SUPABASE_CA, rejectUnauthorized: true }
    : undefined
  const pool = new Pool({ connectionString: process.env.DATABASE_URL, max: 3, ssl })
  const adapter = new PrismaPg(pool)
  return new PrismaClient({ adapter })
}

// Prevent multiple instances in development (Next.js hot reload)
const globalForPrisma = globalThis as unknown as { prisma: PrismaClient }
export const db = globalForPrisma.prisma ?? createClient()
if (process.env.NODE_ENV !== 'production') globalForPrisma.prisma = db
